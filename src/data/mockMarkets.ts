// Helper to generate realistic historical candle series
function generateCandles(basePrice: number, count: number, volatility: number, trend = 0.001): PricePoint[] {
  const candles: PricePoint[] = [];
  let current = basePrice * (1 - (count * trend) / 2);
  const now = Date.now();
  const stepMs = 3600 * 1000 * 24; // 1 day per bar

  for (let i = count; i >= 0; i--) {
    const timestamp = new Date(now - i * stepMs);
    const timeStr = timestamp.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    const changeFactor = 1 + (Math.random() - 0.48) * volatility + trend;
    const open = current;
    current = current * changeFactor;
    const close = current;
    const high = Math.max(open, close) * (1 + Math.random() * (volatility * 0.5));
    const low = Math.min(open, close) * (1 - Math.random() * (volatility * 0.5));
    const volume = Math.floor(basePrice * 10000 * (0.6 + Math.random() * 0.8));

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(basePrice < 5 ? 4 : 2)),
      high: Number(high.toFixed(basePrice < 5 ? 4 : 2)),
      low: Number(low.toFixed(basePrice < 5 ? 4 : 2)),
      close: Number(close.toFixed(basePrice < 5 ? 4 : 2)),
      volume,
    });
  }
  return candles;
}

